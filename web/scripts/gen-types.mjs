// Generate src/api/types.ts from src/api/contracts.schema.json (never edit either by hand).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const schemaPath = resolve(here, '../src/api/contracts.schema.json')
const outPath = resolve(here, '../src/api/types.ts')
const schema = JSON.parse(readFileSync(schemaPath, 'utf8'))
// Property-level `title`s make json-schema-to-typescript emit one alias per field and
// clash with model names (e.g. RunRecord.source_status vs SourceStatus). Drop them and
// title each definition by its own key, so the output uses clean model names only.
function stripTitles(node) {
  if (Array.isArray(node)) return node.map(stripTitles)
  if (node && typeof node === 'object') {
    const out = {}
    for (const [k, v] of Object.entries(node)) {
      if (k === 'title' && typeof v === 'string') continue
      out[k] = stripTitles(v)
    }
    return out
  }
  return node
}
const defs = Object.fromEntries(
  Object.entries(schema.$defs ?? {}).map(([k, v]) => [k, { ...stripTitles(v), title: k }]),
)

// The file is a bag of $defs. Wrap it in a root object that references every def,
// so each one is emitted as a named, exported type.
const root = {
  title: 'ContractsRoot',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(defs).map((k) => [k, { $ref: `#/$defs/${k}` }])),
  $defs: defs,
}

const ts = await compile(root, 'ContractsRoot', {
  bannerComment:
    '/* eslint-disable */\n/**\n * GENERATED by scripts/gen-types.mjs from contracts.schema.json.\n * Do not edit by hand. Run `npm run gen:types`.\n */',
  additionalProperties: false,
  unreachableDefinitions: true,
  enableConstEnums: false,
  inferStringEnumKeysFromValues: false,
  strictIndexSignatures: false,
  format: true,
})
writeFileSync(outPath, ts)
console.log(`wrote ${outPath} (${Object.keys(defs).length} definitions)`)
